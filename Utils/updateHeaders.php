<?php
    error_reporting(E_ALL); ini_set('display_errors', 1);
    $cppFile = "../code/TaggerApp/Connector.mm";
    $DO_EXTERNS = false;
    $IGNORE_GLOBALS =true;
    $ch='';
    print "// Autogenerated: file: $cppFile\n// DO_EXTERNS: $DO_EXTERNS, IGNORE_GLOBALS: $IGNORE_GLOBALS\n";
    $dat = file_get_contents($cppFile);
    
        $cur = 0;
        $len = strlen($dat);
        
        $stack = array();
        $token ="";
        $prevCh = '';
        $commentMode = false;
        $level = 0;
        $inNamespace = false;
        while ( $cur != $len ){
            $prevCh = $ch;
            $ch = $dat[$cur];
            if ( $prevCh == "/" && $ch == "/" )
            {
                $commentMode = true;
            }
            
            if ( $commentMode && ord($ch) != 10){
                $cur++;
                $token .= $ch;
                //print ( "CH $ch ord: ".ord($ch)."\n");
                continue;
            }
            if ( $commentMode ){
                $commentMode = false;
                if ( strpos($token,"@INCLUDE") !== false ){
                    $inc = explode("@INCLUDE ",$token);
                    print "#include $inc[1]\n";
                }
                
                $token = "";
            }
            
            if ( $ch == ';' ){
                if ( $level == 0 && $DO_EXTERNS){
                    print "extern ".trim($token).";\n";
                }
                $token = "";
            }else if ( $ch == '}'){
                $token = "";
                $level--;
                if ( $inNamespace && $level<0 )
                {
                    print "}\n";
                    $level = 0;
                    $inNamespace = false;
                }
            }else if ( $ch == '{'){
                //print("Token nation: \n");
                $t = trim($token);
                
                
                if ( !(strpos( $t,"namespace") !== false )){
                    if ( $level == 0 )
                    {
                        if ( $inNamespace ){
                            print("\t");
                        }
                        if ( $inNamespace || !$IGNORE_GLOBALS )
                        print(trim($token)).";\n";
                    }
                    $level++;
                }
                else{
                    print(trim($token))."{\n";	// namespace
                    $inNamespace=true;
                }
                $token = "";
            }else
            {
                $token .= $ch;
            }
            $cur++;
        }
        
?>
